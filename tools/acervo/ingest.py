def first(values) -> str | None:
    return values[0] if values else None


def clean_name(value: str | None) -> str | None:
    """Removes the prefix the acervo writes before a free name."""
    if not value:
        return None
    text = NAME_PREFIXES.sub("", value).strip().rstrip(".").strip()
    # "editada por por Victor Préalle" repeats the particle.
    text = re.sub(r"^por\s+(?=\S)", "", text, flags=re.I)
    # "Letra de de Castello Netto" is a typo of the archive; the lower-case
    # particle at the beginning is not part of the name.
    text = re.sub(r"^de\s+(?=\S)", "", text)
    return text or None


def mentions(work: dict) -> list[tuple[str, str, str, bool]]:
    """The free names of a work, as the builder will read them.

    The tuples are ``(role, raw, name, may_be_provisional)``.  ``raw`` is the
    value the builder passes to ``People.resolve``; ``name`` is the same value
    without the prefixes the acervo writes.  The names of the “Cópia” field
    that fit no known pattern are **not** names: they are reported separately
    as unstructured copy notes.
    """
    found: list[tuple[str, str, str, bool]] = []
    for score in work.get("scores", []):
        details = score.get("details", {})
        if first(details.get("Arranjo")):
            raw = first(details["Arranjo"])
            found.append(("arranger", raw, clean_name(raw), True))
        if first(details.get("Letra")):
            # the same transformation the expression applies
            raw = re.sub(r"^Letra de\s+", "", first(details["Letra"])).rstrip(".")
            found.append(("lyricist", raw, clean_name(raw), True))
        copy = parse_copy(first(details.get("Cópia")) or "")
        for role, field in (("copyist", "copyist"), ("transcriber", "transcriber"),
                            ("former owner", "former_owner"),
                            ("donor", "donor"), ("editor", "editor")):
            raw = copy.get(field)
            if raw:
                # An editor that matches no person may still be a publishing
                # house, so it must not turn into a provisional person.
                found.append((role, raw, clean_name(raw), role != "editor"))
    return [(role, raw, name, allowed) for role, raw, name, allowed in found if name]


def resolve_person(people: People, aliases: dict[str, str], name: str) -> str | None:
    """Resolves a free name, also trying it without a parenthetical."""
    key = aliases.get(normalize(name)) or people.resolve(name)
    if key:
        return key
    stripped = re.sub(r"\s*\([^)]*\)\s*", " ", name).strip()
    if stripped and stripped != name:
        return people.resolve(stripped)
    return None


def name_owners(cards: list[dict]) -> dict[str, set[str]]:
    """Which person records answer to each normalised name."""
    owners: dict[str, set[str]] = defaultdict(set)
    for card in cards:
        inverted = card.get("inverted") or ""
        values = [card.get("name"), inverted]
        if "," in inverted:
            family, given = inverted.split(",", 1)
            values.append(f"{given.strip()} {family.strip()}")
        for value in values:
            if value:
                owners[normalize(value)].add(str(card["id"]))
    return owners


def provisional_person(name: str, role: str, work_id: str) -> dict:
    """A person the acervo names without giving a record."""
    key = "name:" + normalize(name)
    return {
        "id": key,
        "name": name,
        "inverted": None,
        "roles": [],
        "bio": "",
        "provisional": True,
        "note": (
            f"The archive names this person as {role} in the record of work "
            f"{work_id}, but gives no person record. The identification is "
            "provisional."
        ),
    }


def prepare_people(works: list[dict], cards: list[dict], aliases: dict[str, str],
                   issues: Issues) -> list[dict]:
    """Indexes the cards and creates a provisional person per free name.

    ``aliases`` is extended with the raw values of the acervo, so that the
    builder resolves exactly the strings it reads.  Returns the provisional
    persons, so that the caller can pass them to the builder as extra persons
    (provisional persons have no acervo card, so they must not be modelled as
    cards).
    """
    people = People(cards, EXTRA_PERSONS, aliases=aliases, merged=MERGED_CARDS)
    owners = name_owners(cards + EXTRA_PERSONS)
    provisional: dict[str, dict] = {}

    for work in works:
        for role, raw, name, allowed in mentions(work):
            key = resolve_person(people, aliases, name)
            if key:
                aliases.setdefault(normalize(raw), key)
                candidates = owners.get(normalize(name), set())
                if len(candidates) > 1:
                    issues.add(
                        "ambiguous_person_name", work["id"],
                        f"{role} {name!r} matches {len(candidates)} person records: "
                        + ", ".join(sorted(candidates)),
                    )
                continue
            if not allowed:
                continue
            key = "name:" + normalize(name)
            if key not in provisional:
                provisional[key] = provisional_person(name, role, work["id"])
                issues.add(
                    "provisional_person", work["id"],
                    f"{role} {name!r} → {ids.person(key)}",
                )
            aliases.setdefault(normalize(raw), key)

    return list(provisional.values())


# ---------------------------------------------------------------------------
# places
# ---------------------------------------------------------------------------

def prepare_places(cards: list[dict], issues: Issues) -> list[dict]:
    """The curated places plus the birth places of the harvested persons."""
    places: dict[str, dict] = {}
    by_norm: dict[str, str] = {}
    for place in PLACES:
        places[place["key"]] = dict(place)
        by_norm[normalize(place["key"])] = place["key"]

    for card in cards:
        raw = (card.get("birth_place") or "").strip()
        if not raw:
            continue
        name = place_key(raw)
        if not name:
            continue
        if normalize(name) in NOT_A_PLACE:
            issues.add("place_not_identified", card["id"], raw)
            continue
        existing = by_norm.get(normalize(name))
        if existing:
            continue

        place = {"key": name, "name": name}
        match = re.match(r"^(.*?)\s*[-\u2013]\s*([A-Z]{2})\s*$", raw)
        unit = match.group(2) if match else ""
        if unit in BRAZILIAN_UNITS:
            place["country"] = "Brazil"
            place["description"] = f"{name} - {unit}, Brazil."
        else:
            issues.add(
                "place_without_country", card["id"],
                f"{raw!r}: no Brazilian federal unit; the country is not asserted",
            )
        places[name] = place
        by_norm[normalize(name)] = name

    return sorted(places.values(), key=lambda place: normalize(place["key"]))


