def prepare_institutions(works: list[dict], people: People, issues: Issues) -> list[dict]:
    """The curated institutions plus the publishing houses of the editions."""
    institutions = [dict(institution) for institution in INSTITUTIONS]
    known = {normalize(institution["name"]) for institution in institutions}
    derived: dict[str, dict] = {}

    for work in works:
        for score in work.get("scores", []):
            copy = parse_copy(first(score.get("details", {}).get("Cópia")) or "")
            candidates = [
                ("publisher", copy.get("publisher")),
                ("editor", copy.get("editor")),
            ]
            for role, raw in candidates:
                name = clean_name(raw)
                if not name:
                    continue
                name = institution_name(name)
                norm = normalize(name)
                if norm in PUBLISHER_ALIASES or norm in known or norm in derived:
                    continue
                # An editor that is a person of the acervo is an editor, not
                # a publishing house.
                if role == "editor" and (people.resolve(raw) or people.resolve(name)):
                    continue
                derived[norm] = {"key": name, "name": name, "derived": True}
                known.add(norm)
                issues.add(
                    "derived_institution", work["id"],
                    f"{role} {name!r} has no institution record; created from the name",
                )

    institutions.extend(derived[key] for key in sorted(derived))
    return institutions


# ---------------------------------------------------------------------------
# normalising the records
# ---------------------------------------------------------------------------

def prepare_works(works: list[dict], issues: Issues) -> list[dict]:
    """Normalises the values the model cannot express as they come."""
    for work in works:
        if not (work.get("title") or "").strip():
            work["title"] = f"Untitled (work {work['id']})"
            issues.add("work_without_title", work["id"], "the record has no title")
        if not work.get("composers"):
            issues.add("work_without_composer", work["id"], "the record has no composer")
        for score in work.get("scores", []):
            details = score.get("details", {})
            if details.get("Arranjo"):
                details["Arranjo"] = [clean_name(value) or value for value in details["Arranjo"]]
            if not (score.get("type") or "").strip():
                score["type"] = "Partitura"
                issues.add("score_without_type", work["id"], f"score {score['index']}")
            raw_date = first(details.get("Data"))
            if raw_date and not parse_date(raw_date):
                issues.add("unparsed_date", work["id"], raw_date)
            copy = parse_copy(first(details.get("Cópia")) or "")
            if copy.get("note") and not copy.get("kind"):
                issues.add("unstructured_copy_note", work["id"], copy["note"])
    return works


