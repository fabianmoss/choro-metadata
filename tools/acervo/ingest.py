#: Fake birth places used by the acervo when it does not know the place.
NOT_A_PLACE = {
    "compositor estrangeiro",
    "desconhecido",
    "estrangeiro",
    "ignorado",
    "local nao identificado",
    "nao identificado",
    "sem informacao",
}

#: The two-letter codes of the Brazilian federal units.
BRAZILIAN_UNITS = {
    "AC", "AL", "AP", "AM", "BA", "CE", "DF", "ES", "GO", "MA", "MT", "MS",
    "MG", "PA", "PB", "PR", "PE", "PI", "RJ", "RN", "RS", "RO", "RR", "SC",
    "SP", "SE", "TO",
}

#: Prefixes the acervo writes before a free name in the fields of a score.
NAME_PREFIXES = re.compile(
    r"^\s*(?:arranjo(?:\s+(?:de|por))?|letra(?:\s+de)?|c[oó]pia\s+de)\s*:?\s*",
    re.I,
)

#: The folders the ingestion writes to.  A document of one of these folders
#: that is neither generated in the current run nor listed in the template
#: manifest is a leftover of an earlier run and is removed.
ENTITY_FOLDERS = (
    "bibliography", "expressions", "institutions", "instrumentations",
    "items", "manifestations", "persons", "places", "works",
)

TEMPLATE_MANIFEST = Path(__file__).with_name("template_files.txt")


