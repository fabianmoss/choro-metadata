def load_template_files() -> set[str]:
    """The documents of the upstream template, which are never removed."""
    if not TEMPLATE_MANIFEST.exists():
        return set()
    files = set()
    with open(TEMPLATE_MANIFEST, encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if line and not line.startswith("#"):
                files.add(line)
    return files


def prune_documents(out_dir: str, generated: set[str]) -> int:
    """Removes the entity files that the current run did not generate.

    A provisional person whose name was later resolved to a card, or a work
    that the harvest changed, leaves a file behind; the file would otherwise
    stay in the repository, referring to a state of the data that no longer
    exists.  The documents of the upstream template are preserved through
    ``template_files.txt``.
    """
    templates = load_template_files()
    removed = 0
    for folder in ENTITY_FOLDERS:
        directory = Path(out_dir) / folder
        if not directory.is_dir():
            continue
        for path in directory.glob("*.ttl"):
            relative = f"{folder}/{path.name}"
            if relative in generated or relative in templates:
                continue
            path.unlink()
            removed += 1
    return removed


