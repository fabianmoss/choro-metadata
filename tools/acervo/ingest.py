"""Bulk ingestion of the harvested acervo into the FRBR model.

The harvester (:mod:`tools.acervo.harvest`) writes one JSON record per work
and per person to ``works.jsonl`` and ``cards.jsonl``.  This module turns
those records into the MeLODy files of the repository, in batches, and
writes a report of everything it could not model faithfully.

Scope
-----

The harvest covers the whole acervo, but only the works with at least one
digitised *Partitura* (a score with a PDF) are modelled.  The records that
are already curated in :mod:`tools.acervo.sample_data` are kept even when
they have no digitisation: they are a deliberate sample of the restricted
material, and removing them would drop published entities.

Everything is derived deterministically from the harvested records: re-running
the command after a new harvest rewrites the same files and extends the set.
Names that have no person record in the acervo become provisional persons,
flagged in their description and in the report.

Usage::

    python3 -m tools.acervo.ingest --out .
    python3 -m tools.acervo.ingest --limit 100        # first batch only

The report is written to ``docs/acervo-ingest-issues.md`` (summary) and
``docs/acervo-ingest-issues.csv`` (one row per issue).
"""

