# the ingestion
# ---------------------------------------------------------------------------

def ingest(harvest_dir: str, out_dir: str, issues_md: str, issues_csv: str,
           limit: int = 0, verbose: bool = False, prune: bool = False) -> dict:
    """Builds the entity files from the harvest and writes the report."""
    harvest = Path(harvest_dir)
    issues = Issues()

    harvested_works, work_errors = read_jsonl(harvest / "works.jsonl")
    harvested_cards, card_errors = read_jsonl(harvest / "cards.jsonl")
    # The names of the composer links are HTML-escaped in the page.
    for work in harvested_works.values():
        for composer in work.get("composers", []):
            if composer.get("name"):
                composer["name"] = html.unescape(composer["name"]).strip()
    for error in work_errors:
        issues.add("harvest_error_work", error.get("id"), str(error.get("error")))
    for error in card_errors:
        issues.add("harvest_error_card", error.get("id"), str(error.get("error")))

    # -- works -------------------------------------------------------------
    selected: dict[str, dict] = {
        work_id: work for work_id, work in harvested_works.items() if digitised(work)
    }
    skipped = [work_id for work_id, work in harvested_works.items()
               if not digitised(work)]
    for work_id in skipped:
        issues.add("skipped_work_without_digitisation", work_id, "no Partitura has a PDF")

    # Curated records that the harvest has not reached yet, or that are
    # deliberately kept without digitisation.
    for work in WORKS:
        if work["id"] in selected:
            continue
        selected[work["id"]] = work
        if digitised(work):
            issues.add("curated_work", work["id"],
                       "kept from the sample even though the harvest does not cover it")
        else:
            issues.add("curated_work_without_digitisation", work["id"],
                       "kept from the sample although no Partitura has a PDF")

    works = [selected[key] for key in sorted(selected, key=lambda value: int(value))]
    if limit:
        works = works[:limit]

    # -- persons -----------------------------------------------------------
    cards: dict[str, dict] = {}
    for card_id, card in harvested_cards.items():
        cards[card_id] = dict(card)
    for card in CARDS:
        card_id = str(card["id"])
        cards[card_id] = {**cards.get(card_id, {"id": card_id}), **card}
    cards = [cards[key] for key in sorted(cards, key=lambda value: int(value) if value.isdigit() else value)]

    # Persons without a name cannot be modelled; they are reported below.
    named_cards = []
    for card in cards:
        if (card.get("name") or "").strip():
            named_cards.append(card)
        else:
            issues.add("person_without_name", card["id"],
                       card.get("url") or "the record has no title")
    cards = named_cards

    # Composer records that the card harvest has not reached yet: the work
    # still knows the name of the composer, so the person is modelled with
    # that name until the record arrives.
    by_card = {str(card["id"]) for card in cards}
    for work in works:
        for composer in work.get("composers", []):
            card_id = str(composer.get("card"))
            if card_id in by_card:
                continue
            cards.append({
                "id": card_id,
                "name": composer.get("name") or f"Composer {card_id}",
                "inverted": None,
                "roles": [],
                "bio": "",
                "provisional": True,
                "note": (
                    "The work record names this composer, but the person record "
                    "has not been harvested yet. The identification is provisional."
                ),
            })
            by_card.add(card_id)
            issues.add("composer_card_not_harvested", work["id"],
                       f"card {card_id} ({composer.get('name')})")

    aliases = dict(ALIASES)
    provisional = prepare_people(works, cards, aliases, issues)
    people = People(cards, EXTRA_PERSONS + provisional, aliases=aliases,
                    merged=MERGED_CARDS)

    # -- other entities ----------------------------------------------------
    places = prepare_places(cards, issues)
    for place in places:
        if not place.get("geonames"):
            issues.add("place_without_geonames", place["key"],
                       "no GeoNames identifier; the place is modelled by name")
    institutions = prepare_institutions(works, people, issues)
    for institution in institutions:
        if institution.get("derived") and not institution.get("location"):
            issues.add("institution_without_location", institution["key"],
                       "created from the name of an edition; the place is unknown")

    # The publication event requires a publishing place, which the acervo
    # does not record; when the house has no place, the event is omitted and
    # the publisher stays linked by the contribution of the manifestation.
    by_name = {normalize(institution["name"]): institution
               for institution in institutions}
    for work in works:
        for score in work.get("scores", []):
            copy = parse_copy(first(score.get("details", {}).get("Cópia")) or "")
            name = publisher_name(copy, by_name)
            if name and not by_name[normalize(name)].get("location"):
                issues.add(
                    "publication_event_omitted", work["id"],
                    f"publisher {name!r} has no known place of publication",
                )

    works = prepare_works(works, issues)

    # The instrumentation of the archive uses many spellings; every
    # signature without a curated label is modelled with the archive's
    # words, and the instruments without a LOC term are reported.
    signatures = set()
    for work in works:
        for score in work.get("scores", []):
            instruments = score.get("details", {}).get("Instrumentação") or []
            if instruments:
                signatures.add(tuple(normalize(value) for value in instruments))
    for signature in sorted(signatures):
        if signature not in INSTRUMENTATION_LABELS:
            issues.add("instrumentation_without_label", " + ".join(signature),
                       "the archive's words are used as the label")
        for instrument in signature:
            base = re.sub(r"\s+\d+$", "", instrument)
            if instrument not in INSTRUMENT_TERMS and base not in INSTRUMENT_TERMS:
                issues.add("instrument_without_loc_term", instrument,
                           "no Library of Congress medium-of-performance term")

    # -- emit --------------------------------------------------------------
    files = build(
        works,
        cards,
        EXTRA_PERSONS + provisional,
        places,
        institutions,
        BIBLIOGRAPHY,
        instrumentation_labels=INSTRUMENTATION_LABELS,
        instrument_terms=INSTRUMENT_TERMS,
        aliases=aliases,
        merged=MERGED_CARDS,
        countries=COUNTRIES,
        out_dir=out_dir,
        verbose=verbose,
    )

    # A limited run is a test or the first batch of a longer harvest: it must
    # not delete the documents of the batches that are not in memory.  The
    # caller decides, because only it knows whether the harvest is canonical.
    generated = {f"{folder}/{name}.ttl" for folder, name in files}
    removed = prune_documents(out_dir, generated) if prune else 0

    context = {
        "works_total": len(harvested_works),
        "cards_total": len(harvested_cards),
        "works_digitised": sum(1 for work in harvested_works.values() if digitised(work)),
        "works_modelled": len(works),
        "cards_modelled": len({key for key in people.people}),
        "stale_removed": removed,
    }
    issues.write(Path(issues_md), Path(issues_csv), context)

    print(f"works: {len(works)} modelled "
          f"({context['works_digitised']} digitised in the harvest, "
          f"{len(skipped)} skipped)")
    print(f"persons: {len(people.people)}")
    print(f"files: {len(files)}")
    print(f"issues: {len(issues.rows)}")
    for category, count in issues.counts.most_common():
        print(f"  {category}: {count}")
    return context


def main(argv=None) -> int:
    default_harvest = os.environ.get("ACERVO_DATA", ".cache/acervo")
    parser = argparse.ArgumentParser(
        description="Map the harvested acervo records to the MeLODy entity files.",
        epilog="The problems found are reported in docs/acervo-ingest-issues.md.",
    )
    parser.add_argument("--harvest", default=default_harvest,
                        help="directory with works.jsonl and cards.jsonl")
    parser.add_argument("--out", default=".", help="target directory")
    parser.add_argument("--issues", default="docs/acervo-ingest-issues.md")
    parser.add_argument("--issues-csv", default="docs/acervo-ingest-issues.csv")
    parser.add_argument("--limit", type=int, default=0,
                        help="model only the first N works (for testing)")
    parser.add_argument("--no-prune", action="store_true",
                        help="keep the documents that the current run does not generate")
    parser.add_argument("--prune", action="store_true",
                        help="also prune when --harvest is not the default directory")
    parser.add_argument("--quiet", action="store_true")
    arguments = parser.parse_args(argv)

    # Pruning is only safe when the run covers the whole harvest: while the
    # harvest grows, a work that has not been collected yet must keep the
    # documents of the earlier batches.
    canonical = os.path.abspath(arguments.harvest) == os.path.abspath(default_harvest)
    prune = (
        not arguments.limit
        and not arguments.no_prune
        and harvest_complete(arguments.harvest)
        and (canonical or arguments.prune)
    )

    ingest(
        arguments.harvest,
        os.path.abspath(arguments.out),
        arguments.issues,
        arguments.issues_csv,
        limit=arguments.limit,
        verbose=not arguments.quiet,
        prune=prune,
    )
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
