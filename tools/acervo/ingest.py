class Issues:
    """Collects the problems found while mapping the acervo."""

    def __init__(self) -> None:
        self.rows: list[tuple[str, str, str]] = []
        self.counts: Counter[str] = Counter()
        self._seen: set[tuple[str, str, str]] = set()

    def add(self, category: str, subject: str, detail: str) -> None:
        row = (category, str(subject), detail)
        if row in self._seen:
            return
        self._seen.add(row)
        self.rows.append(row)
        self.counts[category] += 1

    def extend(self, category: str, subject: str, details) -> None:
        for detail in details:
            self.add(category, subject, detail)

    # -- output ------------------------------------------------------------
    def write(self, markdown: Path, table: Path, context: dict) -> None:
        markdown.parent.mkdir(parents=True, exist_ok=True)
        table.parent.mkdir(parents=True, exist_ok=True)

        with open(table, "w", newline="", encoding="utf-8") as handle:
            writer = csv.writer(handle)
            writer.writerow(["category", "subject", "detail"])
            writer.writerows(sorted(self.rows))

        lines = [
            "# Acervo ingestion issues",
            "",
            "Generated by `python3 -m tools.acervo.ingest`; do not edit by hand.",
            "The complete list is in `docs/acervo-ingest-issues.csv`.",
            "",
            "## Harvest",
            "",
            f"- works harvested: {context['works_total']}",
            f"- persons harvested: {context['cards_total']}",
            f"- works with digitised scores: {context['works_digitised']}",
            f"- works modelled (including the curated sample): {context['works_modelled']}",
            f"- persons modelled: {context['cards_modelled']}",
            f"- stale documents removed: {context['stale_removed']}",
            "",
            "## Summary",
            "",
            "| Category | Count |",
            "| --- | ---: |",
        ]
        for category, count in sorted(self.counts.items(), key=lambda item: (-item[1], item[0])):
            lines.append(f"| `{category}` | {count} |")
        if not self.counts:
            lines.append("| — | 0 |")

        lines += ["", "## Details", ""]
        by_category: dict[str, list[tuple[str, str]]] = defaultdict(list)
        for category, subject, detail in self.rows:
            by_category[category].append((subject, detail))
        for category in sorted(by_category):
            entries = by_category[category]
            lines.append(f"### `{category}` ({len(entries)})")
            lines.append("")
            for subject, detail in entries[:200]:
                lines.append(f"- **{subject}** — {detail}")
            if len(entries) > 200:
                lines.append(
                    f"- … and {len(entries) - 200} more in "
                    "`docs/acervo-ingest-issues.csv`."
                )
            lines.append("")

        markdown.write_text("\n".join(lines), encoding="utf-8")


